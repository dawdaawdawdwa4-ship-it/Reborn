import fs from 'node:fs';
const file=new URL('../message.txt',import.meta.url);
const original=fs.readFileSync(file,'utf8');
let source=original.replaceAll('\r\n','\n');
const module=fs.readFileSync(new URL('../tools/AutoBuild.lua',import.meta.url),'utf8').trimEnd();
const start='-- EMBEDDED AUTO BUILD BEGIN',end='-- EMBEDDED AUTO BUILD END';
const block=start+'\n-- Generated by scripts/embed-build.mjs.\nlocal AutoBuild=(function()\n'+module+'\nend)()\n'+end;
if(source.includes(start))source=source.slice(0,source.indexOf(start))+block+source.slice(source.indexOf(end)+end.length);
else source=source.replace('-- EMBEDDED FARM LOGIC END','-- EMBEDDED FARM LOGIC END\n\n'+block);
const output=source.replaceAll('\n','\r\n');
if(process.argv.includes('--check')){if(output!==original)throw Error('Run node scripts/embed-build.mjs');console.log('Embedded Auto Build matches source');}
else fs.writeFileSync(file,output);
