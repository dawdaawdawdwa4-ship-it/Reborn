import fs from 'node:fs';
const path=new URL('../message.txt',import.meta.url);
const original=fs.readFileSync(path,'utf8');
let source=original.replaceAll('\r\n','\n');
const logic=fs.readFileSync(new URL('../tools/FarmLogic.lua',import.meta.url),'utf8').trimEnd();
const start='-- EMBEDDED FARM LOGIC BEGIN',end='-- EMBEDDED FARM LOGIC END';
const block=start+'\n-- Generated by scripts/embed-farm.mjs.\nlocal FarmLogic = (function()\n'+logic+'\nend)()\n'+end;
if(source.includes(start)) source=source.slice(0,source.indexOf(start))+block+source.slice(source.indexOf(end)+end.length);
else source=source.replace('-- EMBEDDED CAPTURE END','-- EMBEDDED CAPTURE END\n\n'+block);
const output=source.replaceAll('\n','\r\n');
if(process.argv.includes('--check')) {if(output!==original) throw Error('Run node scripts/embed-farm.mjs');console.log('Embedded farm logic matches source');}
else fs.writeFileSync(path,output);
