import fs from 'node:fs';
const path=new URL('../message.txt',import.meta.url);
const original=fs.readFileSync(path,'utf8');
let source=original.replaceAll('\r\n','\n');
const module=fs.readFileSync(new URL('../tools/MobFarm.lua',import.meta.url),'utf8').trimEnd();
const start='-- EMBEDDED MOB FARM BEGIN',end='-- EMBEDDED MOB FARM END';
const block=start+'\n-- Generated by scripts/embed-mobs.mjs.\nRemoteCatalog.MobFarmModule=(function()\n'+module+'\nend)()\n'+end;
if(source.includes(start)) source=source.slice(0,source.indexOf(start))+block+source.slice(source.indexOf(end)+end.length);
else source=source.replace('-- EMBEDDED FARM LOGIC END','-- EMBEDDED FARM LOGIC END\n\n'+block);
const output=source.replaceAll('\n','\r\n');
if(process.argv.includes('--check')) {if(output!==original) throw Error('Run node scripts/embed-mobs.mjs');console.log('Embedded mob farm matches source');}
else fs.writeFileSync(path,output);
